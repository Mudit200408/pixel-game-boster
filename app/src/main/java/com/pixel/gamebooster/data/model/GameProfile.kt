package com.pixel.gamebooster.data.model

import com.pixel.gamebooster.data.db.entity.GameProfileEntity

data class GameProfile(
    val packageName: String,
    val customized: Boolean = false,
    val fpsOverride: Int = 0,
    val lockRefreshRate: Boolean = true,
    val boostRam: Boolean = true,
    val cachedFreezer: Boolean = true,
    val disableAutoBrightness: Boolean = true,
    val disableQuickTap: Boolean = true,
    val lockBackGesture: Boolean = false,
    val interventionMode: Int = 2,
    val stabilizeWifi: Boolean = true,
    val wifiLowLatency: Boolean = true,
    val wifiSuppressScans: Boolean = true,
    val wifiLockSufficiency: Boolean = true,
    val wifiPreventArp: Boolean = true,
    val blockBatterySaver: Boolean = true,
    val pauseAutoSync: Boolean = true,
    val disablePrivateDns: Boolean = true,
    val interruptionMode: Int = 1,
    val callHandlingMode: Int = 0,
    val suspendedApps: Set<String> = emptySet(),
    val lastPlayedTimestamp: Long = 0L,
)

fun GameProfileEntity.toDomain(): GameProfile = GameProfile(
    packageName = packageName,
    customized = customized,
    fpsOverride = fpsOverride,
    lockRefreshRate = lockRefreshRate,
    boostRam = boostRam,
    cachedFreezer = cachedFreezer,
    disableAutoBrightness = disableAutoBrightness,
    disableQuickTap = disableQuickTap,
    lockBackGesture = lockBackGesture,
    interventionMode = interventionMode,
    stabilizeWifi = stabilizeWifi,
    wifiLowLatency = wifiLowLatency,
    wifiSuppressScans = wifiSuppressScans,
    wifiLockSufficiency = wifiLockSufficiency,
    wifiPreventArp = wifiPreventArp,
    blockBatterySaver = blockBatterySaver,
    pauseAutoSync = pauseAutoSync,
    disablePrivateDns = disablePrivateDns,
    interruptionMode = interruptionMode,
    callHandlingMode = callHandlingMode,
    suspendedApps = suspendedApps,
    lastPlayedTimestamp = lastPlayedTimestamp,
)

